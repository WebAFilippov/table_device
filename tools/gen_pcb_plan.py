    # драйвер: J3.7..10 -> J_DRV (сигналы)
    ("#c0c", 0.7, [j3(10), (60, j3(10)[1]), (60, 54), (14, 54)]),
    ("#c0c", 0.7, [j3(9),  (60, j3(9)[1]),  (60, 56.5), (14, 56.5)]),
    ("#c0c", 0.7, [j3(8),  (60, j3(8)[1]),  (60, 59), (14, 59)]),
