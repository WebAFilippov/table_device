def pad(x, y, label=""):
    return (f'<circle cx="{x:.1f}" cy="{y:.1f}" r="1.6" fill="none" stroke="#000" stroke-width="0.4"/>'
            + (f'<text x="{x:.1f}" y="{y - 2.6:.1f}" font-size="2.4" text-anchor="middle" fill="#000">{label}</text>' if label else ""))

parts = ['<?xml version="1.0" encoding="UTF-8"?>',
         '<svg xmlns="http://www.w3.org/2000/svg" width="110mm" height="85mm" viewBox="0 0 110 85" font-family="Arial">',
         '<rect x="0.3" y="0.3" width="109.4" height="84.4" fill="#fff" stroke="#000" stroke-width="0.6"/>',
         '<text x="55" y="3.5" font-size="3" text-anchor="middle">План-схема платы 110x85 (ЛУТ). Линии = связи, не дорожки.</text>']

# компоненты
for name, x, y, w, h, col in COMP:
    parts.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="none" stroke="{col}" stroke-width="0.5"/>')
    parts.append(f'<text x="{x + w/2:.1f}" y="{y + h/2:.1f}" font-size="2.6" text-anchor="middle" fill="{col}">{name}</text>')

# пины заголовков DevKitC
for n in range(1, 23):
    x, y = j1(n)
    parts.append(pad(x, y, str(n)))
    x, y = j3(n)
    parts.append(pad(x, y, str(n)))

# пины дисплея и энкодера
for i in range(14):
    parts.append(pad(100, 8 + i * PITCH, str(i + 1)))
for i in range(4):
    parts.append(pad(30, 62 + i * PITCH, str(i + 1)))

# неты
for col, w, pts in NETS:
    d = "M " + " L ".join(f"{x:.1f},{y:.1f}" for x, y in pts)
    parts.append(f'<path d="{d}" fill="none" stroke="{col}" stroke-width="{w}" opacity="0.85"/>')

parts.append('</svg>')

os.makedirs(os.path.dirname(os.path.abspath(OUT)), exist_ok=True)
with open(OUT, "w", encoding="utf-8") as f:
    f.write("\n".join(parts))
print("written:", os.path.abspath(OUT))
